// Writes app/assets/css/mana.css and app/assets/fonts/mana.woff2 from
// mana-font: only the symbols the app can show, as one WOFF2 file (#101).
// mana-font ships 400 KB of WOFF (plus EOT/TTF/SVG) with watermarks, guild
// and clan marks, and nearly 200 keyword icons the app never shows.
// Run with `npm run fonts:mana` after mana-font updates or the app starts
// using another ability or counter icon.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import postcss from 'postcss';
import subsetFont from 'subset-font';

const root = process.cwd();
const pkg = join(root, 'node_modules/mana-font');

/** Families the app never shows. Card text symbols stay. */
const DROPPED = [
  'ability', // Kept only where the app names one (modifiers).
  'counter', // Same.
  'watermark',
  'guild',
  'clan',
  'school',
  'polis',
  'party',
  'dfc',
  'artist',
  'vanguard',
  'defense',
  'battle',
  'loyalty',
  'ci',
  'power',
  'toughness',
  'saga',
  'level',
  'flashback',
  'tap-alt',
  'tap-3ed',
];

function* files(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* files(path);
    else if (/\.(vue|ts)$/.test(entry.name)) yield path;
  }
}

// Ability and counter icons the app names, e.g. in MtgConcepts.ts.
const named = new Set();
for (const file of files(join(root, 'app')))
  for (const [, name] of readFileSync(file, 'utf8').matchAll(
    /ms-((?:ability|counter)-[a-z-]+)/g,
  ))
    named.add(name);

const classOf = (selector) => selector.match(/\.ms-([a-z0-9-]+)/)?.[1];
const dropped = (selector) => {
  const name = classOf(selector);
  if (!name || named.has(name)) return false;
  return DROPPED.some(
    (family) => name === family || name.startsWith(family + '-'),
  );
};

const css = postcss.parse(readFileSync(join(pkg, 'css/mana.css'), 'utf8'));
const codepoints = new Set();

css.walkAtRules('font-face', (rule) => {
  let family;
  rule.walkDecls('font-family', (d) => (family = d.value.replaceAll('"', '')));
  if (family !== 'Mana') return rule.remove(); // MPlantin: loyalty only.
  rule.walkDecls('src', (d) => d.remove());
  rule.append({
    prop: 'src',
    value: 'url("../fonts/mana.woff2") format("woff2")',
  });
  // A tiny file; hide symbols until it's in rather than flash fallback boxes.
  rule.append({ prop: 'font-display', value: 'block' });
});

css.walkRules((rule) => {
  const kept = rule.selectors.filter((s) => !dropped(s));
  if (!kept.length) return rule.remove();
  rule.selectors = kept;
  if (!kept.some((s) => /::?(before|after)/.test(s))) return;
  rule.walkDecls('content', (d) => {
    const text = d.value
      .slice(1, -1)
      .replace(/\\([0-9a-f]{1,6})\s?/gi, (_, hex) =>
        String.fromCodePoint(parseInt(hex, 16)),
      );
    for (const ch of text) codepoints.add(ch);
  });
});

const font = readFileSync(join(pkg, 'fonts/mana.ttf'));
const woff2 = await subsetFont(font, [...codepoints].join(''), {
  targetFormat: 'woff2',
});

mkdirSync(join(root, 'app/assets/fonts'), { recursive: true });
writeFileSync(join(root, 'app/assets/fonts/mana.woff2'), woff2);
const header = `/* Generated by \`npm run fonts:mana\` from mana-font ${
  JSON.parse(readFileSync(join(pkg, 'package.json'))).version
}. Don't edit. */\n`;
writeFileSync(join(root, 'app/assets/css/mana.css'), header + css.toString());
console.log(
  `${codepoints.size} glyphs, ${(woff2.length / 1024).toFixed(1)} KB WOFF2`,
);
