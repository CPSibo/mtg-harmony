/**
 * The service worker, generated at build time (#169). It precaches the app
 * shell so the installed app opens without a network: the page, its bundles,
 * fonts, the manifest and icons. Scryfall requests and card images go to the
 * network as before.
 *
 * - Pages: network first, falling back to the cached shell after
 *   `NAVIGATION_TIMEOUT_MS` or when offline, so a deploy shows on the next load.
 * - Other same-origin files: cache first. Their names are content-hashed.
 * - A new build installs a new cache and takes over at once. It keeps the cache
 *   before it too, so a tab still running the old build can load its lazy chunks
 *   (the Add Card and Event log windows) after Cloudflare has dropped them.
 *
 * Build-time only: `vite.config.ts` calls these and emits `/sw.js`.
 */

export const CACHE_PREFIX = 'mtg-harmony-shell-';
export const NAVIGATION_TIMEOUT_MS = 3000;

/** Public files the shell needs. Others (the share image) stay online-only. */
const PUBLIC_SHELL = /^(favicon\.ico|manifest\.webmanifest|icons\/.+\.png)$/;
/** Build output the shell needs: scripts, styles and fonts. */
const BUNDLE_SHELL = /\.(js|css|woff2?)$/;

/**
 * The URLs to precache, from the build's own files and the public folder's,
 * as root-relative paths, sorted so the same build gives the same list.
 */
export function precacheList(
  bundleFiles: string[],
  publicFiles: string[],
): string[] {
  const files = [
    ...bundleFiles.filter((f) => BUNDLE_SHELL.test(f) && f !== 'sw.js'),
    ...publicFiles.filter((f) => PUBLIC_SHELL.test(f)),
  ];
  return ['/', ...[...new Set(files)].sort().map((f) => `/${f}`)];
}

/** The worker's source, for a build `version` that precaches `files`. */
export function serviceWorkerSource(version: string, files: string[]): string {
  return `// Generated by vite.config.ts from app/pwa/serviceWorker.ts. Don't edit.
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE = PREFIX + ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
const TIMEOUT = ${NAVIGATION_TIMEOUT_MS};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Keep this build's cache and the one before it; drop older ones.
      const shells = (await caches.keys()).filter((k) => k.startsWith(PREFIX) && k !== CACHE);
      const previous = shells.at(-1);
      await Promise.all(shells.filter((k) => k !== previous).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(page(request));
    return;
  }
  // ignoreVary: module scripts are CORS requests with an Origin header, and a
  // server's Vary: Origin would otherwise miss the copies install cached.
  event.respondWith(
    caches.match(request, { ignoreVary: true }).then((hit) => hit || fetch(request)),
  );
});

/** The page from the network, or the cached shell when that's slow or fails. */
async function page(request) {
  const network = fetch(request);
  const timeout = new Promise((resolve) => setTimeout(resolve, TIMEOUT));
  try {
    const response = await Promise.race([network, timeout]);
    if (response && response.ok) return response;
  } catch {
    // Offline: fall through to the cache.
  }
  const shell = await caches.match('/', { cacheName: CACHE, ignoreVary: true });
  return shell || (await caches.match('/', { ignoreVary: true })) || network;
}
`;
}
